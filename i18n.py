def t(key: str, lang: str = 'zh', **kwargs) -> str:
    """Get translated string. Falls back to zh if key/lang missing."""
    entry = STRINGS.get(key, {})
    # Check for neutral (no-language) string first
    text = entry.get('_neutral') or entry.get(lang) or entry.get('zh', f'[{key}]')
    if kwargs:
        text = text.format(**kwargs)
    return text
